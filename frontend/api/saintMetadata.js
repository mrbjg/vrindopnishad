const getSaintMetadata = (slug) => {
  if (!slug) return null;
  const cleanSlug = slug.toLowerCase().replace(/-maharaj$/, '').trim();
  if (cleanSlug.includes('haridas')) return SAINT_METADATA['haridas'];
  if (cleanSlug.includes('harivansh')) return SAINT_METADATA['hit-harivansh'];
  if (cleanSlug.includes('vyas')) return SAINT_METADATA['hariram-vyas'];
  if (cleanSlug.includes('dhruv')) return SAINT_METADATA['dhruvdas'];
  if (cleanSlug.includes('premanand')) return SAINT_METADATA['premanand-ji-maharaj'];
  return null;
};

